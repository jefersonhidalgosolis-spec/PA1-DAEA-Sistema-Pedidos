package com.isil.edu.pe.spedidos.service.impl; 
 
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import com.isil.edu.pe.spedidos.client.reportes.PedidoReporteRestClient;
import com.isil.edu.pe.spedidos.exception.PedidoException;
import com.isil.edu.pe.spedidos.service.PedidoRevisionService;
import java.math.BigDecimal;
import java.sql.Timestamp;
import java.time.LocalDateTime;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.core.ParameterizedTypeReference;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.web.client.ResourceAccessException;
import org.springframework.web.client.RestClient;

@SpringBootTest
@ActiveProfiles("test")
class PedidoRevisionServiceImplTest {

  @Autowired
  private PedidoRevisionService pedidoRevisionService;

  @Autowired
  private JdbcTemplate jdbcTemplate;

  @BeforeEach
  void setUp() {
    jdbcTemplate.execute("""
        CREATE TABLE IF NOT EXISTS pedido_revision (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
          pedido_id BIGINT NOT NULL,
          observacion VARCHAR(500) NOT NULL,
          fecha_revision TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
          CONSTRAINT pk_pedido_revision PRIMARY KEY (id),
          CONSTRAINT fk_pedido_revision_pedido
            FOREIGN KEY (pedido_id) REFERENCES pedido (id)
            ON DELETE RESTRICT
            ON UPDATE CASCADE,
          CONSTRAINT uq_pedido_revision_pedido UNIQUE (pedido_id)
        )
        """);
    jdbcTemplate.update("DELETE FROM pedido_revision");
    jdbcTemplate.update("DELETE FROM pedido");
  }

  @Test
  @DisplayName("Debe confirmar la transacción actualizando pedido y registrando en pedido_revision")
  void commitTransaccionalCuandoRevisionEsValida() {
    // Arrange
    Long pedidoId = insertarPedidoPendiente(
        "Ana Torres",
        "LAP-001",
        "Laptop",
        new BigDecimal("2500.00"),
        1,
        new BigDecimal("2500.00")
    );
    String observacion = "Pedido validado y listo para despacho";

    // Act
    pedidoRevisionService.revisarPedido(pedidoId, observacion);

    // Assert
    Boolean revisado = jdbcTemplate.queryForObject(
        "SELECT revisado FROM pedido WHERE id = ?",
        Boolean.class,
        pedidoId
    );
    Integer totalRevisiones = jdbcTemplate.queryForObject(
        "SELECT COUNT(*) FROM pedido_revision WHERE pedido_id = ?",
        Integer.class,
        pedidoId
    );
    String observacionGuardada = jdbcTemplate.queryForObject(
        "SELECT observacion FROM pedido_revision WHERE pedido_id = ?",
        String.class,
        pedidoId
    );

    assertTrue(Boolean.TRUE.equals(revisado));
    assertEquals(1, totalRevisiones);
    assertEquals(observacion, observacionGuardada);
  }

  @Test
  @DisplayName("Debe hacer rollback y no dejar cambios parciales cuando falla la segunda escritura")
  void rollbackIntegracionCuandoFallaSegundaEscrituraEnPedidoRevision() {
    // Arrange
    Long pedidoId = insertarPedidoPendiente(
        "Luis Mendoza",
        "MOU-002",
        "Mouse",
        new BigDecimal("80.00"),
        2,
        new BigDecimal("160.00")
    );
    jdbcTemplate.update(
        "INSERT INTO pedido_revision (pedido_id, observacion, fecha_revision) VALUES (?, ?, CURRENT_TIMESTAMP(6))",
        pedidoId,
        "Registro previo que fuerza conflicto en segunda escritura"
    );

    // Act
    assertThrows(
        PedidoException.class,
        () -> pedidoRevisionService.revisarPedido(pedidoId, "Intento de revisión duplicada")
    );

    // Assert
    Boolean revisado = jdbcTemplate.queryForObject(
        "SELECT revisado FROM pedido WHERE id = ?",
        Boolean.class,
        pedidoId
    );
    Integer totalRevisiones = jdbcTemplate.queryForObject(
        "SELECT COUNT(*) FROM pedido_revision WHERE pedido_id = ?",
        Integer.class,
        pedidoId
    );

    assertEquals(Boolean.FALSE, revisado);
    assertEquals(1, totalRevisiones);
  }

  @Test
  @DisplayName("Debe lanzar PedidoException controlada sin exponer traza técnica si el servicio remoto no responde")
  void clienteHttpDebeTraducirIndisponibilidadAExcepcionControlada() {
    // Arrange
    RestClient restClientMock = mock(RestClient.class, org.mockito.Answers.RETURNS_DEEP_STUBS);
    when(restClientMock.get()
        .uri(anyString(), any(Object[].class))
        .retrieve()
        .body(any(ParameterizedTypeReference.class)))
        .thenThrow(new ResourceAccessException("Connection refused: localhost/127.0.0.1:8083"));

    PedidoReporteRestClient cliente = new PedidoReporteRestClient(
        restClientMock,
        "http://localhost:8083/pedidos-reportes-service/api/v1/pedidos"
    );

    // Act
    PedidoException error = assertThrows(
        PedidoException.class,
        () -> cliente.listarPorEstado("PENDIENTE")
    );

    // Assert
    assertTrue(error.getMessage().contains("8083"));
    assertTrue(error.getMessage().contains("no está disponible"));
    verify(restClientMock, never()).post();
  }

  private Long insertarPedidoPendiente(
      String cliente,
      String productoCodigo,
      String productoNombre,
      BigDecimal precioUnitario,
      int cantidad,
      BigDecimal total
  ) {
    jdbcTemplate.update(
        """
        INSERT INTO pedido (cliente, producto_codigo, producto_nombre, precio_unitario, cantidad, total, fecha, revisado)
        VALUES (?, ?, ?, ?, ?, ?, ?, FALSE)
        """,
        cliente,
        productoCodigo,
        productoNombre,
        precioUnitario,
        cantidad,
        total,
        Timestamp.valueOf(LocalDateTime.now())
    );
    return jdbcTemplate.queryForObject("SELECT MAX(id) FROM pedido", Long.class);
  }
}